def secucode(code: str) -> str:
    """裸代码 → 东财 SECUCODE（6开头沪市 / 其余深市；银行池内无科创板）"""
    return f"{code}.SH" if code.startswith("6") else f"{code}.SZ"

def tcode(code: str) -> str:
    """裸代码 → 腾讯行情代码前缀（股票）"""
    return ("sh" if code.startswith(("6",)) else "sz") + code

